import { z } from 'zod';
import { hasPermission } from '@/lib/permissions';
import { createClient } from '@/lib/supabase/server';
import { getDocumentLabelMetadata, isAutogeneratedMetadata } from '@/lib/attachments';
import { assembleDocumentsPdf, safePdfFileName } from '@/lib/storage/document-pdf';
import { documentsForLot, getRequiredReleaseDocuments } from '@/lib/utils/release-requirements';
import { compareDocumentsByCategory } from '@/lib/types/client';
import { RELEASE_DOCUMENT_TYPES } from '@/lib/types/title';

const UUID_PATTERN =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

const requestBodySchema = z.object({
  documentIds: z.array(z.string().uuid()).min(1).optional(),
});

interface AttachmentRow {
  attachment_id: string;
  file_category: string;
  file_path: string;
  property_id: string | null;
  uploaded_at: string;
  metadata: Record<string, unknown> | null;
}

interface TitlePacketRow {
  client_id: string;
  property_id: string;
  is_legacy_transferred: boolean;
  client: { full_name: string } | null;
  property: { block_number: number; lot_number: number } | null;
}

async function handlePacketPdf(titleId: string, requestedIds?: string[]): Promise<Response> {
  if (!UUID_PATTERN.test(titleId)) {
    return Response.json({ error: 'Invalid title id' }, { status: 400 });
  }

  const supabase = await createClient();
  const { data: authData } = await supabase.auth.getUser();
  if (!authData.user) {
    return Response.json({ error: 'Authentication required' }, { status: 401 });
  }
  if (!(await hasPermission('legal.read', authData.user.id))) {
    return Response.json({ error: 'You do not have access to title documents' }, { status: 403 });
  }

  const { data: title, error: titleError } = await supabase
    .from('land_title')
    .select(
      'client_id, property_id, is_legacy_transferred, client:client_id(full_name), property:property_id(block_number, lot_number)'
    )
    .eq('title_id', titleId)
    .maybeSingle<TitlePacketRow>();

  if (titleError || !title) {
    return Response.json({ error: 'Land title record not found' }, { status: 404 });
  }

  const { data: rawDocs, error: docsError } = await supabase
    .from('file_attachment')
    .select('attachment_id, file_category, file_path, property_id, uploaded_at, metadata')
    .eq('client_id', title.client_id)
    .order('uploaded_at', { ascending: false })
    .returns<AttachmentRow[]>();

  if (docsError) {
    console.error('Failed to load title packet documents for PDF:', docsError.message);
    return Response.json({ error: 'Unable to load title documents' }, { status: 500 });
  }

  // Scope eligible files to this lot + personal documents so other lots are never leaked.
  const eligible = documentsForLot(rawDocs ?? [], title.property_id);
  const releaseTypeSet = new Set<string>(RELEASE_DOCUMENT_TYPES);
  const requiredTypes = getRequiredReleaseDocuments(title.is_legacy_transferred);

  const latestReleaseByType = new Map<string, AttachmentRow>();
  for (const doc of eligible) {
    if (releaseTypeSet.has(doc.file_category) && !latestReleaseByType.has(doc.file_category)) {
      latestReleaseByType.set(doc.file_category, doc);
    }
  }

  const orderedPacketDocs: AttachmentRow[] = [];
  for (const type of requiredTypes) {
    const match = latestReleaseByType.get(type);
    if (match) orderedPacketDocs.push(match);
  }

  const referenceDocs = eligible
    .filter((doc) => !releaseTypeSet.has(doc.file_category))
    .sort((a, b) =>
      compareDocumentsByCategory(
        { document_type: a.file_category, uploaded_at: a.uploaded_at },
        { document_type: b.file_category, uploaded_at: b.uploaded_at }
      )
    );

  const validIdDocs = referenceDocs.filter((doc) => !doc.property_id && doc.file_category === 'Valid ID');
  const otherReferenceDocs = referenceDocs.filter(
    (doc) => !(!doc.property_id && doc.file_category === 'Valid ID')
  );

  let selectedDocs: AttachmentRow[];
  if (requestedIds) {
    const allowedSet = new Set(requestedIds);
    const canonicalCandidates = [...orderedPacketDocs, ...validIdDocs, ...otherReferenceDocs];
    selectedDocs = canonicalCandidates.filter((doc) => allowedSet.has(doc.attachment_id));
  } else {
    selectedDocs = [...orderedPacketDocs, ...validIdDocs];
  }

  if (selectedDocs.length === 0) {
    return Response.json({ error: 'No matching uploaded documents found for this packet' }, { status: 404 });
  }

  try {
    const pdfBytes = await assembleDocumentsPdf(
      selectedDocs.map((doc) => ({
        file_path: doc.file_path,
        file_category: doc.file_category,
        uploaded_at: doc.uploaded_at,
        is_autogenerated: isAutogeneratedMetadata(doc.metadata),
        label: getDocumentLabelMetadata(doc.metadata),
      }))
    );

    const lotTag = title.property
      ? `Block_${title.property.block_number}_Lot_${title.property.lot_number}`
      : 'Lot';
    const clientTag = safePdfFileName(title.client?.full_name ?? 'client', 'client');
    const fileName = `Turnover_Packet_${lotTag}_${clientTag}.pdf`;

    return new Response(Buffer.from(pdfBytes), {
      headers: {
        'Content-Type': 'application/pdf',
        'Content-Disposition': `attachment; filename="${fileName}"`,
        'Cache-Control': 'private, no-store',
      },
    });
  } catch (error) {
    console.error('Failed to assemble title packet PDF:', error);
    return Response.json(
      { error: error instanceof Error ? error.message : 'Unable to create PDF packet' },
      { status: 500 }
    );
  }
}

export async function GET(
  _request: Request,
  { params }: { params: Promise<{ titleId: string }> }
) {
  const { titleId } = await params;
  return handlePacketPdf(titleId);
}

export async function POST(
  request: Request,
  { params }: { params: Promise<{ titleId: string }> }
) {
  const { titleId } = await params;
  let body: unknown = {};
  try {
    body = await request.json();
  } catch {
    body = {};
  }

  const parsed = requestBodySchema.safeParse(body);
  if (!parsed.success) {
    return Response.json({ error: 'Select at least one valid document to include' }, { status: 400 });
  }

  return handlePacketPdf(titleId, parsed.data.documentIds);
}
