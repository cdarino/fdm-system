import { describe, it, expect, beforeAll, afterAll } from "vitest";
import { createProjectArea } from "@/lib/actions/project-areas";
import { createPropertyLot } from "@/lib/actions/properties";
import { createClient } from "@/lib/actions/clients";
import { createLandTitle } from "@/lib/actions/titles";
import { getReleaseDocuments } from "@/lib/actions/release-documents";
import {
  createBillingLedger,
  getBillingLedgerById,
  postBillingPayment,
  markAccountClearedByBilling,
  uploadBillingClearanceDocument,
} from "@/lib/actions/billing";
import {
  loginAsAdmin,
  hardDeleteTestProperty,
  hardDeleteTestClient,
  hardDeleteTestProjectArea,
} from "../framework/session";
import { unwrap } from "../framework/action-helper";
import { uniqueNameSuffix } from "../framework/fake-data";

describe("Billing Clearance Documents Integration", () => {
  const testPropertyIds: string[] = [];
  const testClientIds: string[] = [];
  const testProjectAreaIds: string[] = [];

  beforeAll(async () => {
    await loginAsAdmin();
  });

  afterAll(async () => {
    for (const id of testPropertyIds) {
      try {
        await hardDeleteTestProperty(id);
      } catch {}
    }
    for (const id of testClientIds) {
      try {
        await hardDeleteTestClient(id);
      } catch {}
    }
    for (const id of testProjectAreaIds) {
      try {
        await hardDeleteTestProjectArea(id);
      } catch {}
    }
  });

  it("uploads clearance documents with autogenerated and manual provenance, verified in legal release packet", async () => {
    const suffix = uniqueNameSuffix();

    const areaRes = await createProjectArea({
      name: `Clearance Test Area ${suffix}`,
      boundary: [
        [0, 0],
        [0, 10],
        [10, 10],
        [10, 0],
      ],
    });
    const area = unwrap(areaRes);
    testProjectAreaIds.push(area.project_area_id);

    const clientRes = await createClient({
      full_name: `Clearance Client ${suffix}`,
      contact_number: "09123456789",
      address: "123 Clearance St, Davao City",
      civil_status: "Single",
    });
    const client = unwrap(clientRes);
    testClientIds.push(client.client_id);

    const lotRes = await createPropertyLot({
      project_area_id: area.project_area_id,
      block_number: 7,
      lot_number: 14,
      area_size: 150,
      price_per_sqm: 1000,
      status: "Reserved",
    });
    const lot = unwrap(lotRes);
    testPropertyIds.push(lot.property_id);

    const ledgerRes = await createBillingLedger({
      clientId: client.client_id,
      propertyId: lot.property_id,
      contractPrice: 150000,
      downpayment: 150000,
      termMonths: 1,
      firstDueDate: "2026-12-01",
      dueDay: 1,
      penaltyRate: 0,
    });
    const ledger = unwrap(ledgerRes);

    // Settle the account balance
    await postBillingPayment({
      accountId: ledger.accountId,
      paymentDate: "2026-11-01",
      amount: 150000,
      receiptNumber: `OR-${suffix}`,
      paymentMethod: "cash",
      waivePenalty: true,
    });

    // 1. Upload auto-generated SOA
    const soaContent = new Uint8Array([37, 80, 68, 70, 45, 49, 46, 52]); // %PDF-1.4 header
    const soaFile = new File([soaContent], "SOA-Auto.pdf", { type: "application/pdf" });
    const soaFormData = new FormData();
    soaFormData.set("file", soaFile);
    soaFormData.set("document_type", "SOA");
    soaFormData.set("is_autogenerated", "true");

    const soaUploadRes = await uploadBillingClearanceDocument(ledger.accountId, soaFormData);
    expect(soaUploadRes.success).toBe(true);
    const soaDoc = unwrap(soaUploadRes);
    expect(soaDoc.document_type).toBe("SOA");
    expect(soaDoc.is_autogenerated).toBe(true);

    // 2. Upload manual Payment History
    const paymentsContent = new Uint8Array([37, 80, 68, 70, 45, 49, 46, 52]);
    const paymentsFile = new File([paymentsContent], "Payments-Manual.pdf", { type: "application/pdf" });
    const paymentsFormData = new FormData();
    paymentsFormData.set("file", paymentsFile);
    paymentsFormData.set("document_type", "Payment History");
    paymentsFormData.set("is_autogenerated", "false");

    const paymentsUploadRes = await uploadBillingClearanceDocument(ledger.accountId, paymentsFormData);
    expect(paymentsUploadRes.success).toBe(true);
    const paymentsDoc = unwrap(paymentsUploadRes);
    expect(paymentsDoc.document_type).toBe("Payment History");
    expect(paymentsDoc.is_autogenerated).toBe(false);

    // 3. Mark cleared by billing
    const clearRes = await markAccountClearedByBilling(ledger.accountId);
    expect(clearRes.success).toBe(true);

    // 4. Create land title in Legal
    const titleRes = await createLandTitle({ property_id: lot.property_id });
    expect(titleRes.success).toBe(true);
    const title = unwrap(titleRes);

    // 5. Fetch release documents for Legal's turnover packet
    const releaseDocs = await getReleaseDocuments(title.title_id);
    const releaseSoa = releaseDocs.find((d) => d.document_type === "SOA");
    const releasePayments = releaseDocs.find((d) => d.document_type === "Payment History");

    expect(releaseSoa).toBeDefined();
    expect(releaseSoa?.is_autogenerated).toBe(true);

    expect(releasePayments).toBeDefined();
    expect(releasePayments?.is_autogenerated).toBe(false);
  });
});
