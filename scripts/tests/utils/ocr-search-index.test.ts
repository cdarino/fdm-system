import { describe, it, expect, beforeAll, afterAll } from "vitest";
import { faker } from "@faker-js/faker";
import {
  indexEntityText,
  getEntityIndex,
  deleteEntityIndex,
  searchDocumentText,
  getUnindexedDocuments,
} from "@/lib/actions/search-index";
import { createClient, createClientDocument } from "@/lib/actions/clients";
import { isAutogeneratedMetadata } from "@/lib/attachments";
import { tidyExtractedText } from "@/lib/ocr/extract-document-text";
import { loginAsAdmin, logoutUser, hardDeleteTestClient } from "../framework/session";
import { unwrap } from "../framework/action-helper";

describe("OCR Search Index & Text Extraction", () => {
  beforeAll(async () => {
    await loginAsAdmin();
  });

  afterAll(async () => {
    await logoutUser();
  });

  it("cleans and tidies raw extracted OCR text", () => {
    const rawConfetti = "  \n  12   \n ,,, \n  Contract of Sale  Between Parties  \n \n   Lot 45 Block 12  \n";
    const cleaned = tidyExtractedText(rawConfetti);
    expect(cleaned).toContain("Contract of Sale Between Parties");
    expect(cleaned).toContain("Lot 45 Block 12");
    expect(cleaned).not.toContain(",,,");
  });

  it("indexes, retrieves, and deletes document text in search_index", async () => {
    const testEntityId = faker.string.uuid();
    const testContent = "Agreement regarding Transfer of Lot 18 Block 99 in Davao Millennium";
    const testKeywords = "Valid ID Land Title Transfer";

    // 1. Index document
    const indexed = await indexEntityText({
      entity_id: testEntityId,
      entity_type: "client_document",
      content: testContent,
      keywords: testKeywords,
    });
    expect(indexed.entity_id).toBe(testEntityId);
    expect(indexed.content).toBe(testContent);

    // 2. Retrieve indexed document
    const retrieved = await getEntityIndex("client_document", testEntityId);
    expect(retrieved).not.toBeNull();
    expect(retrieved?.content).toBe(testContent);
    expect(retrieved?.keywords).toBe(testKeywords);

    // 3. Delete from index
    await deleteEntityIndex("client_document", testEntityId);
    const afterDelete = await getEntityIndex("client_document", testEntityId);
    expect(afterDelete).toBeNull();
  });

  it("returns unindexed documents query correctly", async () => {
    const unindexed = await getUnindexedDocuments(10);
    expect(Array.isArray(unindexed)).toBe(true);
    // Each unindexed item must have valid metadata
    for (const doc of unindexed) {
      expect(doc.attachment_id).toBeDefined();
      expect(doc.file_name).toBeDefined();
    }
  });

  it("detects autogenerated metadata flags", () => {
    expect(isAutogeneratedMetadata({ autogenerated: true })).toBe(true);
    expect(isAutogeneratedMetadata({ source: "autogenerated" })).toBe(true);
    expect(isAutogeneratedMetadata({ autogenerated: false, source: "manual_upload" })).toBe(false);
    expect(isAutogeneratedMetadata(null)).toBe(false);
  });

  it("searches document text and returns folder and upload metadata", async () => {
    const uniqueToken = `ocrhit${Date.now()}`;
    const client = unwrap(await createClient({ full_name: faker.person.fullName() }));
    let documentId: string | null = null;

    try {
      const doc = await createClientDocument(client.client_id, {
        document_type: "Valid ID",
        file_path: `/uploads/clients/${uniqueToken}.pdf`,
      });
      documentId = doc.document_id;

      await indexEntityText({
        entity_id: doc.document_id,
        entity_type: "client_document",
        content: `Official clearance verification for ${uniqueToken} in Davao`,
        keywords: `Valid ID ${client.full_name}`,
      });

      const hits = await searchDocumentText(uniqueToken);
      const hit = hits.find((h) => h.document_id === doc.document_id);
      expect(hit).toBeDefined();
      expect(hit?.client_id).toBe(client.client_id);
      expect(hit?.client_name).toBe(client.full_name);
      expect(hit?.property_id).toBeNull();
      expect(hit?.property_label).toBeNull();
      expect(hit?.property_location).toBeNull();
      expect(hit?.uploaded_at).toBeTruthy();
      expect(hit?.is_autogenerated).toBe(false);
      expect(hit?.excerpt).toContain(uniqueToken);
    } finally {
      if (documentId) {
        await deleteEntityIndex("client_document", documentId).catch(() => {});
      }
      await hardDeleteTestClient(client.client_id).catch(() => {});
    }
  });
});
