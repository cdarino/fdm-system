export const PERSONAL_DOC_TYPES = ['Valid ID'] as const;
export type PersonalDocType = (typeof PERSONAL_DOC_TYPES)[number];

export const PROPERTY_DOC_TYPES = [
  'Contract',
  'Deed of Sale',
  'SOA',
  'Payment History',
  'Certificate of Ownership',
  'Title Copy',
] as const;
export type PropertyDocType = (typeof PROPERTY_DOC_TYPES)[number];

/** Every kind of client document, in the order the upload menu lists them. */
export const DOC_TYPES = [
  ...PERSONAL_DOC_TYPES,
  ...PROPERTY_DOC_TYPES,
] as const;

export type StandardDocType = (typeof DOC_TYPES)[number];
export type DocType = StandardDocType | (string & {});

/** How each type reads on screen. The only contract FDM signs with buyers is the Contract to Sell. */
export const DOC_TYPE_LABEL: Record<string, string> = {
  'Valid ID': 'Valid ID',
  Contract: 'Contract to Sell',
  'Deed of Sale': 'Deed of Sale',
  SOA: 'Statement of Account (SOA)',
  'Payment History': 'Payment history',
  'Certificate of Ownership': 'Certificate of Ownership',
  'Title Copy': 'Copy of the title',
  Other: 'Other',
};

export function getDocumentTypeLabel(type: string): string {
  return (DOC_TYPE_LABEL as Record<string, string>)[type] ?? type;
}

export function compareDocumentsByCategory(
  a: { document_type: string; uploaded_at?: string | null },
  b: { document_type: string; uploaded_at?: string | null }
): number {
  const indexA = (DOC_TYPES as readonly string[]).indexOf(a.document_type);
  const indexB = (DOC_TYPES as readonly string[]).indexOf(b.document_type);

  if (indexA !== -1 && indexB !== -1) {
    if (indexA !== indexB) return indexA - indexB;
  } else if (indexA !== -1) {
    return -1;
  } else if (indexB !== -1) {
    return 1;
  } else {
    const labelDiff = getDocumentTypeLabel(a.document_type).localeCompare(
      getDocumentTypeLabel(b.document_type),
      undefined,
      { sensitivity: 'base' }
    );
    if (labelDiff !== 0) return labelDiff;
  }

  return (b.uploaded_at ?? '').localeCompare(a.uploaded_at ?? '');
}

