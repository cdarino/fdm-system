/**
 * The `SearchIndex` from the domain model: extracted text for any entity,
 * keyed by type so land titles (MVP 2) can index into the same table.
 */
export type IndexableEntity = 'client_document' | 'land_title' | 'land_title_notice';

export interface SearchIndexEntry {
  index_id: string;
  entity_id: string;
  entity_type: string;
  content: string | null;
  keywords: string | null;
  indexed_at: string;
}

export interface IndexEntityInput {
  entity_id: string;
  entity_type: IndexableEntity;
  content?: string | null;
  keywords?: string | null;
}

export interface DocumentSearchHit {
  document_id: string;
  client_id: string;
  client_name: string;
  document_type: string;
  file_path: string;
  file_name: string | null;
  label: string | null;
  property_id: string | null;
  property_label: string | null;
  property_location: string | null;
  uploaded_at: string | null;
  is_autogenerated: boolean;
  /** Text around the match, so a result shows why it was returned. */
  excerpt: string | null;
}

export interface UnindexedDocument {
  attachment_id: string;
  file_name: string;
  file_path: string;
  file_category: string;
  mime_type: string;
  entity_type: string;
  client_id: string | null;
  client_name?: string;
  uploaded_at: string;
}

/** Where a document is in the OCR pipeline, tracked in the browser only. */
export type OcrStatus = 'idle' | 'running' | 'done' | 'failed';
