import 'server-only';

import { PDFDocument, rgb, type PDFImage } from 'pdf-lib';
import { GetObjectCommand } from '@aws-sdk/client-s3';
import { getStorageBucket, getStorageClient } from '@/lib/storage/s3';
import { getDocumentTypeLabel } from '@/lib/types/client';

const PAGE_WIDTH = 595.28;
const PAGE_HEIGHT = 841.89;
const PAGE_MARGIN = 42;
const LABEL_HEIGHT = 24;

export interface PdfSourceDocument {
  file_path: string;
  file_category: string;
  uploaded_at: string;
  is_autogenerated?: boolean;
  label?: string | null;
}

export function safePdfFileName(value: string, fallback = 'documents'): string {
  return (
    value
      .normalize('NFKD')
      .replace(/[^a-zA-Z0-9_-]+/g, '_')
      .replace(/^_+|_+$/g, '') || fallback
  );
}

function sanitizeWinAnsiText(value: string): string {
  return value
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/[\u201C\u201D]/g, '"')
    .replace(/[\u2013\u2014]/g, '-')
    .replace(/[^\x20-\xFF]/g, '');
}

function fileExtension(path: string): string {
  return path.split('/').pop()?.split('.').pop()?.toLowerCase() ?? '';
}

export async function assembleDocumentsPdf(
  documents: PdfSourceDocument[]
): Promise<Uint8Array> {
  const output = await PDFDocument.create();
  const storage = getStorageClient();
  const bucket = getStorageBucket();

  for (const document of documents) {
    const object = await storage.send(
      new GetObjectCommand({ Bucket: bucket, Key: document.file_path })
    );
    if (!object.Body) {
      throw new Error(`Stored file is empty: ${document.file_category}`);
    }
    const bytes = await object.Body.transformToByteArray();
    const extension = fileExtension(document.file_path);

    if (extension === 'pdf') {
      const source = await PDFDocument.load(bytes, { ignoreEncryption: false });
      const pages = await output.copyPages(source, source.getPageIndices());
      for (const page of pages) output.addPage(page);
      continue;
    }

    let image: PDFImage;
    if (extension === 'jpg' || extension === 'jpeg') {
      image = await output.embedJpg(bytes);
    } else if (extension === 'png') {
      image = await output.embedPng(bytes);
    } else {
      throw new Error(`Unsupported uploaded file format: ${extension || 'unknown'}`);
    }

    const page = output.addPage([PAGE_WIDTH, PAGE_HEIGHT]);
    const docLabel = getDocumentTypeLabel(document.file_category);
    const customLabel = document.label?.trim();
    const prefix = document.is_autogenerated ? 'Autogenerated' : 'Uploaded';
    const uploadedDate = new Date(document.uploaded_at).toLocaleDateString('en-PH', {
      dateStyle: 'medium',
      timeZone: 'Asia/Manila',
    });
    const caption = sanitizeWinAnsiText(
      `${docLabel}${customLabel ? ` - ${customLabel}` : ''} · ${prefix} ${uploadedDate}`
    );
    page.drawText(caption, {
      x: PAGE_MARGIN,
      y: PAGE_HEIGHT - PAGE_MARGIN,
      size: 12,
      color: rgb(0.2, 0.25, 0.3),
    });

    const availableWidth = PAGE_WIDTH - PAGE_MARGIN * 2;
    const availableHeight = PAGE_HEIGHT - PAGE_MARGIN * 2 - LABEL_HEIGHT;
    const scale = Math.min(availableWidth / image.width, availableHeight / image.height);
    const width = image.width * scale;
    const height = image.height * scale;
    page.drawImage(image, {
      x: (PAGE_WIDTH - width) / 2,
      y: PAGE_MARGIN + (availableHeight - height) / 2,
      width,
      height,
    });
  }

  return output.save();
}
